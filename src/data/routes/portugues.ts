/**
 * 依據使用者選擇之分支（中央線 vs 海岸線），動態建構出單調遞增 cumulativeKm 之完整航點陣列
 */
export function getPortuguesWaypoints(branchId: 'central' | 'costa' = 'central'): Waypoint[] {
  const specificList = branchId === 'costa' ? coastalSpecificWaypoints : centralSpecificWaypoints
  const result: Waypoint[] = []

  // 1. 起點 Porto
  result.push({ ...portoWaypoint, cumulativeKm: 0 })
  let currentKm = 0

  // 2. 分支獨有航點
  for (const wp of specificList) {
    currentKm += wp.segmentKm
    result.push({
      id: wp.id,
      localName: wp.localName,
      spanishName: wp.spanishName,
      chineseName: wp.chineseName,
      coordinates: wp.coordinates,
      cumulativeKm: Number(currentKm.toFixed(1)),
      elevationM: wp.elevationM,
      hasAlbergue: wp.hasAlbergue,
      hasPharmacy: wp.hasPharmacy,
      hasSupermarket: wp.hasSupermarket,
      isMajorCity: wp.isMajorCity,
      routeVariant: 'COMMON',
    })
  }

  // 3. 匯流共線航點 (Redondela ➔ Santiago)
  for (let i = 0; i < mergedSharedWaypoints.length; i++) {
    const wp = mergedSharedWaypoints[i]
    // 首站 Redondela 依分支動態決定進城里程：
    // 中央線自 Enxertade 為 4.8km；海岸線自 Chapela 依 Gronze 實測為 7.9km
    const segKm = i === 0 ? (branchId === 'costa' ? 7.9 : 4.8) : wp.segmentKm
    currentKm += segKm
    result.push({
      id: wp.id,
      localName: wp.localName,
      spanishName: wp.spanishName,
      chineseName: wp.chineseName,
      coordinates: wp.coordinates,
      cumulativeKm: Number(currentKm.toFixed(1)),
      elevationM: wp.elevationM,
      hasAlbergue: wp.hasAlbergue,
      hasPharmacy: wp.hasPharmacy,
      hasSupermarket: wp.hasSupermarket,
      isMajorCity: wp.isMajorCity,
      routeVariant: 'COMMON',
    })
  }

  return result
}
